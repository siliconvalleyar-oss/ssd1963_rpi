inline void draw_char(SSD1963& lcd, uint16_t x, uint16_t y, char c, uint16_t fg, uint16_t bg) {
    if (c < 32 || c > 126) c = ' ';
    uint8_t idx = c - 32;
    for (uint8_t row = 0; row < FONT_H; row++) {
        uint8_t bits = FONT8x8[idx][row];
        for (uint8_t col = 0; col < FONT_W; col++) {
            lcd.draw_pixel(x + col, y + row, (bits & (1 << (7 - col))) ? fg : bg);
        }
    }
}

inline void draw_text(SSD1963& lcd, uint16_t x, uint16_t y, const char* text, uint16_t fg, uint16_t bg) {
    while (*text) {
        if (*text == '\n') {
            x = 0;
            y += FONT_H + 2;
        } else if (*text == '\t') {
            x += FONT_W * 4;
        } else {
            draw_char(lcd, x, y, *text, fg, bg);
            x += FONT_W + 1;
            if (x + FONT_W > LCD_WIDTH) {
                x = 0;
                y += FONT_H + 2;
            }
        }
        text++;
    }
}

inline void draw_text_centered(SSD1963& lcd, uint16_t y, const char* text, uint16_t fg, uint16_t bg) {
    uint16_t len = 0;
    const char* p = text;
    while (*p) { if (*p != '\n') len++; p++; }
    uint16_t x = (LCD_WIDTH - len * (FONT_W + 1)) / 2;
    draw_text(lcd, x, y, text, fg, bg);
}
