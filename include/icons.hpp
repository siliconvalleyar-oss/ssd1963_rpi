// For batch/fill drawing small icon directly to LCD (fast, uses set_area + batch)
inline void draw_icon(SSD1963& lcd, uint16_t x, uint16_t y, const uint8_t icon[32], uint16_t fg, uint16_t bg) {
    lcd.set_area(x, y, x + ICON_W - 1, y + ICON_H - 1);
    lcd.write_command(0x2C); // WRITE_MEMORY_START
    lcd.write_batch_start();
    for (uint8_t row = 0; row < ICON_H; row++) {
        uint16_t row_bits = ((uint16_t)icon[row * 2] << 8) | icon[row * 2 + 1];
        for (int8_t col = ICON_W - 1; col >= 0; col--) {
            lcd.write_batch_data((row_bits >> col) & 1 ? fg : bg);
        }
    }
    lcd.write_batch_end();
}
